// The evidence file: a short, generated account of this run for anyone reading the dashboard's source.
//
// main.ts writes it as dashboard/0-evidence.md so it sorts first. It is built from the same snapshot,
// board and source notes as everything else, in sections ordered by importance, and keeps only the
// whole sections that fit a byte budget (main.ts sets the budget so every page source file stays whole
// in a 65,536-byte text). No figure in it is typed by hand: each is computed in this run.

import { MODEL, SIZE_MAPPINGS, baseValue, tokenClass, type Snapshot } from './model.ts';
import type { BoardRow, buildBoard } from './radar.ts';
import type { Plan, SourceBook } from './plans.ts';
import { stepString } from './plans.ts';

type Row = BoardRow & { plan: Plan };

const usd = (n: number) => (n >= 1e9 ? '$' + (n / 1e9).toFixed(2) + 'B' : n >= 1e6 ? '$' + (n / 1e6).toFixed(1) + 'M' : n >= 1e3 ? '$' + (n / 1e3).toFixed(0) + 'K' : '$' + Math.round(n));
const pct = (n: number | null) => (n === null ? 'n/a' : (n > 0 ? '+' : '') + n.toFixed(1) + '%');
const count = <T,>(xs: T[], f: (x: T) => string) => {
  const c = new Map<string, number>();
  for (const x of xs) c.set(f(x), (c.get(f(x)) ?? 0) + 1);
  return [...c].sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1));
};

/** The sections, most important first. */
export function evidenceSections(snapshot: Snapshot, built: ReturnType<typeof buildBoard>, book: SourceBook | null): string[] {
  const rows = built.rows as Row[];
  const tc = count(snapshot.protocols, tokenClass);
  const wl = rows.filter((r) => r.on_watchlist);
  const below = rows.filter((r) => r.tvl_usd < snapshot.floor_usd).length;
  const out: string[] = [];

  out.push(
    '# Token Radar: evidence for this run\n\n' +
      'Generated by main.ts from the snapshot dated ' + snapshot.as_of + ' (' + snapshot.source + '), model ' + MODEL.version + '. ' +
      'Every number below is computed in this run. zz-data.js carries all ' + rows.length + ' rows for the page and is summarised here, not reproduced.\n\n' +
      '## Coverage\n\n' +
      '- Protocols read: ' + snapshot.protocols.length + '. DefiLlama token record: ' + tc.map(([k, n]) => k + ' ' + n).join(', ') + '.\n' +
      '- Ranked: ' + rows.length + ' rows (' + count(rows, (r) => r.row_class).map(([k, n]) => k + ' ' + n).join(', ') + '); ' + below + ' sit below the ' + usd(snapshot.floor_usd) + ' watchlist floor.\n' +
      '- Watchlist covered: ' + wl.length + '/' + snapshot.watchlist.length + ' (ranks ' + wl.map((r) => r.rank).join(', ') + ').\n' +
      '- Not ranked: ' + built.live.length + ' with a trading token (used only as value comparables), ' + built.unpriced.length + ' recording a token without a market cap, ' + built.setAside.length + ' set aside.\n' +
      '- Plans: ' + rows.filter((r) => r.plan_basis === 'official-source').length + ' rows use official-source steps; ' + rows.filter((r) => r.plan_basis === 'category-checklist').length + ' use category research checklists.\n',
  );

  const unc = rows.filter((r) => r.classification.certainty !== 'clear');
  out.push(
    '## Classification\n\n' +
      '"No token recorded" = no CoinGecko id, ticker or market cap in the record; not proof that none exists or is planned. Recorded tokens never fill the 100-row floor; a snapshot that cannot fill it honestly fails the build.\n\n' +
      '- Certainty: ' + count(rows, (r) => r.classification.certainty).map(([k, n]) => k + ' ' + n).join(', ') + '.\n' +
      '- Set-aside reasons: ' + count(built.setAside, (s) => s.reason.split(' (')[0]!).slice(0, 4).map(([k, n]) => k + ' ' + n).join('; ') + '.\n' +
      unc.slice(0, 1).map((r) => '- ' + r.name + ' (#' + r.rank + ', ' + r.classification.certainty + '): ' + r.classification.reason + '\n').join(''),
  );

  const V = built.validation, sel = V.results.find((x) => x.id === V.selected)!;
  const x3 = (d: number) => 'x/' + Math.pow(10, d).toFixed(1);
  const fxId = ({ size: 'size+factors', 'size+category': 'size+category+factors', category: 'category+factors' } as Record<string, string>)[V.selected];
  const fxv = V.results.find((x) => x.id === fxId);
  out.push(
    '## Validation (held-out, traded tokens)\n\n' +
      V.folds + ' folds fixed by a hash of the slug (sizes ' + V.fold_sizes.join(', ') + '; ' + V.comps + ' tokens with market cap and TVL). Every median, fit and offset is refitted without the held-out fold. ' +
      'Error = median |log10(predicted / actual market cap)| (dex; 0.30 is a factor of 2).\n\n| Mapping | Median dex | Mean | Within x3 |\n|---|---|---|---|\n' +
      V.results.map((x) => '| ' + x.id + (x.id === V.selected ? ' (used)' : '') + ' | ' + x.mdae_dex + ' | ' + x.mae_dex + ' | ' + Math.round(x.within_3x * 100) + '% |\n').join('') +
      '\nSelected: ' + V.reason + '. ' + (fxv ? 'With fixed 7-day growth, listing-age and breadth heuristics: ' + fxv.mdae_dex + ' vs ' + sel.mdae_dex + ' dex, so they are ' + (fxv.id === V.selected ? '' : 'not ') + 'in the value; the page shows them per row as a sensitivity. ' : '') +
      'The same folds picked the mapping, so its error is slightly optimistic (model selection, not an independent final test). It checks a cross-sectional proxy on launched tokens, not launch odds, prices or rewards.\n',
  );

  const ex = [rows[0], rows.find((r) => r.model.sibling < 1 || r.model.cls < 1)].filter((r, i, a): r is Row => !!r && a.indexOf(r) === i);
  out.push(
    '## Valuation\n\n' +
      (SIZE_MAPPINGS.includes(V.selected) ? 'base = exp(a + b ln TVL' + (V.selected.includes('category') ? ' + category offset' : '') + '), a = ' + V.full_fit.a + ', b = ' + V.full_fit.b + ' (OLS on all ' + V.comps + ' traded tokens)' : 'base = TVL x ' + (V.selected === 'global' ? 'all-category' : 'shrunk category') + ' multiple') +
      '; implied = base x related (' + MODEL.sibling_factor + ' when a token-bearing protocol shares the first name word) x class (0.3 for weak rows). Related and class are untested judgement discounts. Range: ' + x3(sel.mdae_dex) + ' (held-out median error), widened per missing field.\n\n' +
      'The listing date is DefiLlama\'s listed_at: a proxy for time without a token, not a launch or founding date. ' +
      'Value is the estimate; Opportunity (0-100) ranks value per dollar of TVL after risk and effort; Confidence (High/Medium/Low) reflects comparable count and missing data, not the chance of a launch.\n\n' +
      'Limits: one snapshot (no supply, unlocks, funding, team intent or prices); comparables are launched tokens and may differ from tokenless ones; set-aside, related-token, risk and effort rules are heuristics with per-row reasons.\n\n' + ex.map((r) => {
        const m = r.model;
        const prod = baseValue(r.tvl_usd, m) * m.growth * m.track * m.breadth * m.sibling * m.cls;
        return '- ' + r.name + ' (#' + r.rank + '): TVL ' + usd(r.tvl_usd) + ' -> base ' + usd(baseValue(r.tvl_usd, m)) + ' (' + m.multiple + 'x TVL)' + (m.growth * m.track * m.breadth !== 1 ? ' x ' + m.growth + ' x ' + m.track + ' x ' + m.breadth : '') + ' x ' + m.sibling + (m.cls !== 1 ? ' x ' + m.cls : '') + ' = ' + usd(prod) + '; board ' + r.implied_value_usd + ' (' + (Math.max(1, Math.round(prod)) === r.implied_value_usd ? 'matches' : 'differs') + '), range ' + usd(r.implied_range_usd[0]) + '-' + usd(r.implied_range_usd[1]) + ', ' + r.confidence + ' confidence. Not in value: 7d ' + pct(r.change_7d) + ', listed ' + (r.age_days ?? 'n/a') + ' days.\n';
      }).join(''),
  );


  const types = new Set<string>();
  const pick: Row[] = [];
  for (const r of rows) if (r.plan_basis === 'official-source' && !types.has(r.plan.product_type) && pick.length < 1) { types.add(r.plan.product_type); pick.push(r); }
  const chk = rows.find((r) => r.plan_basis === 'category-checklist');
  if (chk) pick.push(chk);
  out.push(
    '## Plans (' + pick.length + ' of ' + rows.length + ', as written to board.json)\n\n' +
      'Costs, times, test sizes and horizons are assumptions, not requirements or eligibility conditions. No leverage, wash trading or activity-only transactions. Every plan also opens with an identity gate and ends with an exit step (omitted here).\n\n' +
      pick.map((r, k) => '### ' + r.name + ' (#' + r.rank + ', ' + r.plan.basis + ')\n\nProduct: ' + r.plan.product + ' Access: ' + r.plan.access + '\n\n' +
        r.plan.steps.map((s, i) => (i === 0 || i === r.plan.steps.length - 1 || (k > 0 && i === r.plan.steps.length - 2) ? '' : k > 0 && s.kind === 'gate' ? (i + 1) + '. [Gate · ' + s.basis + '] ' + s.text.split(':')[0] + ' (' + s.time + ').\n' : (i + 1) + '. ' + stepString(s) + '\n')).join('')).join('\n'),
  );

  if (book) {
    const used = rows.filter((r) => book.protocols[r.slug]);
    out.push(
      '## Source reading (' + book.retrieved + ')\n\n' + book.method + '\n\n' +
        'What each source does and does not establish is stored per plan (board.json plan notes, page detail).\n\n' + used.map((r) => '- ' + r.name + ' (' + book.protocols[r.slug]!.product_type + '): ' + book.protocols[r.slug]!.sources.map((s) => s.url.replace(/^https:\/\//, '')).join(' ; ') + '\n').join(''),
    );
  }

  out.push(
    '## Top of the board\n\n| # | Protocol | Category | TVL | 7d | Value | Conf. | Opp. | Plan |\n|---|---|---|---|---|---|---|---|---|\n' +
      rows.slice(0, 12).map((r) => '| ' + r.rank + ' | ' + r.name + (r.on_watchlist ? ' (WL)' : '') + ' | ' + (r.category ?? '-') + ' | ' + usd(r.tvl_usd) + ' | ' + pct(r.change_7d) + ' | ' + usd(r.implied_value_usd) + ' | ' + r.confidence + ' | ' + r.opportunity + ' | ' + (r.plan_basis === 'official-source' ? 'sourced' : 'checklist') + ' |\n').join(''),
  );

  const cats = [...built.cal.byCategory.values()].sort((a, b) => b.comps - a.comps || (a.category < b.category ? -1 : 1)).slice(0, 8);
  out.push(
    '## Category multiples (largest samples)\n\n' + cats.map((c) => '- ' + c.category + ': ' + c.comps + ' comps, raw ' + c.raw_median + ', used ' + c.multiple + ', spread ' + c.spread + (c.examples.length ? ' (' + c.examples.slice(0, 3).join(', ') + ')' : '') + '\n').join(''),
  );
  // Priority: coverage, validation, valuation, plans, classification, limitations, sources, tables.
  const [cov, cls, val, vln, plans, ...rest] = out;
  return [cov!, val!, vln!, cls!, plans!, ...rest];
}

const bytes = (s: string) => new TextEncoder().encode(s).length;

/** Whole sections in order while they fit maxBytes; the first section always goes in. */
export function evidenceText(sections: string[], maxBytes: number): { text: string; kept: number } {
  let text = sections[0]!;
  let kept = 1;
  for (const s of sections.slice(1)) {
    const next = text + '\n' + s;
    if (bytes(next) > maxBytes) break;
    text = next;
    kept++;
  }
  return { text, kept };
}
